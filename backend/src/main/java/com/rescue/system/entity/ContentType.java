package com.rescue.system.entity;

/**
 * Enum representing the type of moderatable content
 * Part of UC405: Content Moderation (Kiểm duyệt nội dung)
 */
public enum ContentType {
    /**
     * Community post (Bài viết cộng đồng)
     */
    POST,

    /**
     * Comment on posts (Bình luận)
     */
    COMMENT,

    /**
     * Service review (Đánh giá dịch vụ)
     */
    REVIEW
}
